# ======================================================
# Noise generation function (same as yours)
# ======================================================
def generate_gaussian_cube(center, edge=3, n_points=100, mean=0, std=0.5):
    cx, cy, cz = center
    r = edge / 2.0  # 1.5 m

    nx = np.random.normal(mean, std, n_points)
    ny = np.random.normal(mean, std, n_points)
    nz = np.random.normal(mean, std, n_points)

    nx = np.clip(nx, -r, r)
    ny = np.clip(ny, -r, r)
    nz = np.clip(nz, -r, r)

    return cx + nx, cy + ny, cz + nz

# ======================================================
# Process ALL Excel files
# ======================================================
files = sorted([f for f in os.listdir(input_dir) if f.endswith(".xlsx")])

print("Total files found:", len(files))

for file in files:
    print(f"\nProcessing → {file}")

    # ---------------------------
    # Load file
    # ---------------------------
    file_path = os.path.join(input_dir, file)
    df = pd.read_excel(file_path)

    print("Original size:", len(df))

    # ---------------------------
    # Downsample 15%
    # ---------------------------
    df_small = df.sample(frac=0.20, random_state=42).reset_index(drop=True)
    print("Downsampled size:", len(df_small))

    # ---------------------------
    # Generate noisy point
    # ---------------------------
    noisy_x, noisy_y, noisy_z = [], [], []

    for i in tqdm(range(len(df_small)), desc="Adding noise"):
        cx = df_small.loc[i, "x"]
        cy = df_small.loc[i, "y"]
        cz = df_small.loc[i, "z"]

        xs, ys, zs = generate_gaussian_cube(center=(cx, cy, cz))
        idx = random.randint(0, 99)

        noisy_x.append(xs[idx])
        noisy_y.append(ys[idx])
        noisy_z.append(zs[idx])

    df_small["x_noisy"] = noisy_x
    df_small["y_noisy"] = noisy_y
    df_small["z_noisy"] = noisy_z

    # ---------------------------
    # Save output
    # ---------------------------
    output_file = file.replace(".xlsx", "_noisy.xlsx")
    output_path = os.path.join(output_dir, output_file)

    df_small.to_excel(output_path, index=False)

    print("Saved →", output_path)

