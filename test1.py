# ============================================================
# 4. LOCAL PCA-BASED RECONSTRUCTION
# ============================================================
def reconstruct_patch(center, tree, points,
                      K=40, samples=80, radius=2.0):
    """
    center : (3,)
    returns : (samples, 3)
    """
    _, idx = tree.query(center[:2].reshape(1, -1), k=K)
    neigh = points[idx[0]]

    # PCA
    mean = neigh.mean(axis=0)
    X = neigh - mean
    _, _, Vt = np.linalg.svd(X)
    t1, t2 = Vt[0], Vt[1]

    # Sample on tangent plane
    u = np.random.uniform(-radius, radius, samples)
    v = np.random.uniform(-radius, radius, samples)

    patch = mean + np.outer(u, t1) + np.outer(v, t2)
    return patch


# ============================================================
# 5. RECONSTRUCT ENTIRE PCD
# ============================================================
reconstructed = []

for c in centers:
    patch = reconstruct_patch(
        c, tree, points,
        K=50,
        samples=120,
        radius=100.0
    )
    reconstructed.append(patch)

