def generate_gaussian_cube(center=(0,0,0), edge=3, n_points=100, mean=0, std=0.5):
    """
    center : actual true point at middle of cube
    edge   : cube edge length in meters (3 m)
    n_points : number of noisy points (100)
    mean   : Gaussian mean
    std    : Gaussian std deviation
    """
    cx, cy, cz = center

    # Radius = half of the cube edge
    r = edge / 2.0   # for 3-meter cube → r = 1.5 m

    # Generate Gaussian noise
    noise_x = np.random.normal(mean, std, n_points)
    noise_y = np.random.normal(mean, std, n_points)
    noise_z = np.random.normal(mean, std, n_points)

    # Clip noise so that points stay inside cube boundaries
    noise_x = np.clip(noise_x, -r, r)
    noise_y = np.clip(noise_y, -r, r)
    noise_z = np.clip(noise_z, -r, r)

    # Create noisy points
    x_points = cx + noise_x
    y_points = cy + noise_y
    z_points = cz + noise_z

    # KDE plot for noise distribution
    plt.figure(figsize=(14,5))
    plt.suptitle("Gaussian Noise KDE for Cube Distribution", fontsize=16)

    plt.subplot(1,3,1)
    sns.kdeplot(noise_x, fill=True, color="blue")
