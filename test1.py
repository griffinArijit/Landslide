import pandas as pd
import numpy as np
from scipy.interpolate import griddata
import plotly.graph_objects as go

# -------------------------------------------------------------
# 1. LOAD ORIGINAL TERRAIN (already in METERS)
# -------------------------------------------------------------
df = pd.read_csv("/content/xyz_with_soilmoisture_fixed.csv")

x = df["x"].values  # already meters
y = df["y"].values  # already meters
z = df["z"].values  # meters

# -------------------------------------------------------------
# 2. LOAD HOLE POINTS (ALSO already in meters)
# -------------------------------------------------------------
df_holes = pd.read_csv("/content/high_slope_high_moisture_top25_z_top0_4_percent.csv")

xh = df_holes["x"].values  # meters
yh = df_holes["y"].values  # meters

# -------------------------------------------------------------
# 3. AUTO GRID RESOLUTION (aspect-aware, data-aware)
# -------------------------------------------------------------
x_range = x.max() - x.min()
y_range = y.max() - y.min()

resolution_per_km = 30
Nx_init = (x_range / 1000) * resolution_per_km
Ny_init = (y_range / 1000) * resolution_per_km

aspect = x_range / max(y_range, 1e-9)
cells_init = Nx_init * Ny_init
max_cells = 4 * len(df)

if cells_init > max_cells:
    cells_target = max_cells
    Ny = int(np.sqrt(cells_target / aspect))
    Nx = int(aspect * Ny)
else:
    Nx = int(Nx_init)
    Ny = int(Ny_init)

Nx = max(Nx, 200)
Ny = max(Ny, 200)

print(f"Grid resolution → Nx={Nx}, Ny={Ny}")

xg = np.linspace(x.min(), x.max(), Nx)
yg = np.linspace(y.min(), y.max(), Ny)
X, Y = np.meshgrid(xg, yg)

# -------------------------------------------------------------
# 4. INTERPOLATE ELEVATION TO REGULAR GRID (FAST LINEAR)
# -------------------------------------------------------------
Z = griddata(
    (x, y),
    z,
    (X, Y),
    method="linear"
)
Z = np.nan_to_num(Z, nan=np.nanmean(z))

# -------------------------------------------------------------
# 4. GLOBAL SETTINGS (bowl physics)
# -------------------------------------------------------------
base_radius = 300      # meters
dr = 50                # random radius variation
base_depth = 1         # meters
dz = 0.5               # random depth variation

# -------------------------------------------------------------
# 5. APPLY RANDOMIZED GAUSSIAN HOLES (SAFE LOOP VERSION)
# -------------------------------------------------------------
total_bowls = np.zeros_like(Z)

for i in range(len(df_holes)):
    hx = xh[i]
    hy = yh[i]

    # Randomized radius and depth
    radius_final = base_radius + np.random.uniform(-dr, dr)
    depth_final  = base_depth  + np.random.uniform(-dz, dz)
    sigma = radius_final / 2

    # Compute bowl effect for this hole
    dx = X - hx
    dy = Y - hy
    R = np.sqrt(dx**2 + dy**2)

    bowl = depth_final * np.exp(-(R**2) / (2 * sigma**2))

    total_bowls -= bowl


# -------------------------------------------------------------
# 6. FINAL TERRAIN
# -------------------------------------------------------------
Z_mod = Z + total_bowls

# -------------------------------------------------------------
# 7. VISUALIZATION
# -------------------------------------------------------------
fig = go.Figure(data=[
    go.Surface(
        x=X,
        y=Y,
        z=Z_mod,
        surfacecolor=total_bowls,
        colorscale="RdBu",
        colorbar=dict(title="dz")
    )
])

fig.update_layout(
    title="Real-Scale Terrain With Gaussian Holes (Optimized)",
    height=900,
    scene=dict(
        aspectmode="manual",
        aspectratio=dict(x=10, y=1, z=1)  # z exaggerated
    )
)

fig.show()

# -------------------------------------------------------------
# 8. SAVE OUTPUT
# -------------------------------------------------------------
df_after = df.copy()

# interpolate modified Z back to original scattered points
points_after = griddata(
    (X.flatten(), Y.flatten()),
    Z_mod.flatten(),
    (x, y),
    method="linear"
)

df_after["z"] = np.nan_to_num(points_after, nan=z)
df_after.to_csv("/content/terrain_after.csv", index=False)
df.to_csv("/content/terrain_before.csv", index=False)

