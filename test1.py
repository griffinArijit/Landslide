K = 20

# ============================================================
# 3. PCA-PLANE SLOPE ESTIMATION
# ============================================================
def local_slope_pca(neighbors):
    """
    neighbors : Nx3 array of XYZ coordinates
    returns slope in degrees using PCA plane fitting
    """
    # Mean center
    mean = neighbors.mean(axis=0)
    centered = neighbors - mean

    # PCA (SVD)
    _, _, Vt = np.linalg.svd(centered)

    # Plane normal
    nx, ny, nz = Vt[-1]

    # Slope relative to horizontal
    slope_rad = np.arctan(np.sqrt(nx*2 + ny*2) / np.abs(nz))
    return np.degrees(slope_rad)


# ============================================================
# 4. CALCULATE SLOPE FOR EACH POINT
# ============================================================
slopes = np.zeros(len(points_xyz))

for i in range(len(points_xyz)):
    # Query neighbors
    _, idx = tree.query(points_xyz[i:i+1, :2], k=K)
    neighbors = points_xyz[idx[0]]

    slopes[i] = local_slope_pca(neighbors)

df["slope_deg"] = slopes

print("Slope calculation done!")
print("Slope Range:", slopes.min(), "to", slopes.max())

